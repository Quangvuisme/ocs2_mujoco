#!/usr/bin/env python3
"""Writes robots/g1/scene_terrain.xml: a straight obstacle course along +x for the Unitree G1.

    x [m]   0.0 ........ start (flat)
            1.5 - 3.3    stairs up   (4 steps, rise 0.08 m, tread 0.45 m)
            3.3 - 4.3    platform    (0.32 m high, 1.0 m long)
            4.3 - 5.65   stairs down (3 steps + floor, tread 0.45 m)
            6.2 - 7.8    rough blocks (0.40 x 0.40 m, 0.02 - 0.06 m high)
            8.4 ........ goal

All terrain geoms are in geom group 0; the MuJoCo elevation mapper ray casts against groups 0/1,
the robot's own geoms are in groups 2 (visual) and 3 (collision).

Usage: generate_terrain.py [output.xml]   (deterministic, no dependencies)
"""
import os
import random
import sys

STEP_RISE = 0.08
STEP_TREAD = 0.45
NUM_STEPS = 4
PLATFORM = 1.0
WIDTH = 1.0  # half width of the course [m]


def box(name, x, y, z_top, hx, hy, rgba):
    hz = z_top / 2.0
    return (f'    <geom name="{name}" type="box" pos="{x:.4f} {y:.4f} {hz:.4f}" size="{hx:.4f} {hy:.4f} {hz:.4f}" '
            f'rgba="{rgba}" material="terrain" friction="1.0 0.01 0.001"/>')


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "robots", "g1", "scene_terrain.xml")
    rng = random.Random(7)
    geoms = []

    # stairs up
    x0 = 1.5
    for k in range(NUM_STEPS):
        shade = 0.55 + 0.06 * (k % 2)
        geoms.append(box(f"stair_up_{k}", x0 + STEP_TREAD * (k + 0.5), 0.0, STEP_RISE * (k + 1), STEP_TREAD / 2, WIDTH,
                         f"{shade:.2f} {shade:.2f} {shade + 0.05:.2f} 1"))
    top = STEP_RISE * NUM_STEPS
    x_platform = x0 + STEP_TREAD * NUM_STEPS
    geoms.append(box("platform", x_platform + PLATFORM / 2, 0.0, top, PLATFORM / 2, WIDTH, "0.50 0.55 0.62 1"))

    # stairs down
    x1 = x_platform + PLATFORM
    for k in range(NUM_STEPS - 1):
        shade = 0.55 + 0.06 * (k % 2)
        geoms.append(box(f"stair_down_{k}", x1 + STEP_TREAD * (k + 0.5), 0.0, top - STEP_RISE * (k + 1), STEP_TREAD / 2,
                         WIDTH, f"{shade:.2f} {shade:.2f} {shade + 0.05:.2f} 1"))

    # rough blocks
    xr = 6.2
    cell = 0.4
    for i in range(4):
        for j in range(5):
            h = rng.uniform(0.02, 0.06)
            g = 0.45 + 0.4 * (h - 0.02) / 0.04
            geoms.append(box(f"rough_{i}_{j}", xr + cell * (i + 0.5), -WIDTH + cell * (j + 0.5), h, cell / 2, cell / 2,
                             f"{g:.2f} {0.9 * g:.2f} {0.7 * g:.2f} 1"))

    xml = f"""<!-- Generated by scripts/generate_terrain.py - edit the script, not this file. -->
<mujoco model="g1_12dof terrain course">
  <include file="g1_12dof.xml"/>

  <statistic center="3 0 0.6" extent="3.0"/>

  <visual>
    <headlight diffuse="0.6 0.6 0.6" ambient="0.3 0.3 0.3" specular="0 0 0"/>
    <rgba haze="0.15 0.25 0.35 1"/>
    <global azimuth="-130" elevation="-20" offwidth="1920" offheight="1080"/>
  </visual>

  <asset>
    <texture type="skybox" builtin="gradient" rgb1="0.3 0.5 0.7" rgb2="0 0 0" width="512" height="3072"/>
    <texture type="2d" name="groundplane" builtin="checker" mark="edge" rgb1="0.2 0.3 0.4" rgb2="0.1 0.2 0.3"
      markrgb="0.8 0.8 0.8" width="300" height="300"/>
    <material name="groundplane" texture="groundplane" texuniform="true" texrepeat="5 5" reflectance="0.2"/>
    <material name="terrain" specular="0.1" shininess="0.1"/>
  </asset>

  <worldbody>
    <light pos="2 0 3" dir="0 0 -1" directional="true" castshadow="false" diffuse="0.4 0.4 0.4"/>
    <geom name="floor" size="0 0 0.05" type="plane" material="groundplane" friction="1.0 0.01 0.001"/>
{os.linesep.join(geoms)}
  </worldbody>
</mujoco>
"""
    with open(out, "w") as f:
        f.write(xml)
    print(f"wrote {out} ({len(geoms)} terrain geoms)")


if __name__ == "__main__":
    main()
