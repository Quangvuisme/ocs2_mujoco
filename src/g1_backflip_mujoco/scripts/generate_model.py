#!/usr/bin/env python3
"""Generates the robot files of g1_backflip_mujoco from the Unitree G1 29-DoF description of wb_humanoid_mpc.

Inputs (git submodule src/wb_humanoid_mpc, BSD-3):
  robot_models/unitree_g1/g1_description/urdf/g1_29dof.urdf   MPC model of wb_humanoid_mpc
  robot_models/unitree_g1/g1_description/urdf/g1_29dof.xml    its MuJoCo model (torque motors)

Outputs (robots/g1_29dof/):
  urdf/g1_29dof_flip.urdf : the same URDF with visual / collision elements removed and a massless root link
                            "flip_base" (see below)
  g1_29dof.xml            : the same MJCF with meshes from the submodule, a 1 kHz time step, torque limits as
                            ctrlrange, no self-collision, foot friction 1.0 and sites at the foot contact frames

The flip_base frame
-------------------
The MPC parameterises the base orientation with ZYX Euler angles, which are singular at a pitch of +-90 deg. A
backflip pitches the pelvis through a full turn, so the MPC base is a frame rotated by +90 deg about the pelvis z axis:
its x axis is the pelvis y axis (the robot's left). The backflip is then a rotation about the base x axis, the last
ZYX angle ("roll"), which is never singular. A robot that faces world +x has base yaw +pi/2.

Usage: generate_model.py [wb_humanoid_mpc dir] [output robots/g1_29dof dir]
"""

import math
import os
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)


def generate_urdf(src, dst):
    tree = ET.parse(src)
    robot = tree.getroot()
    for e in list(robot):
        if e.tag == "mujoco" or e.tag == "material":
            robot.remove(e)
    for link in robot.findall("link"):
        for tag in ("visual", "collision"):
            for e in link.findall(tag):
                link.remove(e)
    links = robot.findall("link")
    first = list(robot).index(links[0])
    joint = ET.Element("joint", {"name": "flip_base_joint", "type": "fixed"})
    ET.SubElement(joint, "origin", {"xyz": "0 0 0", "rpy": "0 0 %.10f" % (-math.pi / 2)})
    ET.SubElement(joint, "parent", {"link": "flip_base"})
    ET.SubElement(joint, "child", {"link": "pelvis"})
    robot.insert(first, joint)
    robot.insert(first, ET.Element("link", {"name": "flip_base"}))
    ET.indent(tree, space="  ")
    with open(dst, "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n')
        f.write("<!-- Generated by g1_backflip_mujoco/scripts/generate_model.py from wb_humanoid_mpc\n"
                "     robot_models/unitree_g1/g1_description/urdf/g1_29dof.urdf: kinematics and inertia only, root link\n"
                "     flip_base (the pelvis turned by -90 deg about z relative to it). -->\n")
        tree.write(f, encoding="unicode")


def generate_mjcf(src, dst, mesh_dir_rel):
    tree = ET.parse(src)
    mj = tree.getroot()
    mj.find("compiler").set("meshdir", mesh_dir_rel)
    # drop the scene of the upstream file (floor, sky, light, camera settings): scene.xml has its own
    for e in list(mj):
        if (e.tag in ("statistic", "visual") or (e.tag == "asset" and e.find("mesh") is None)
                or (e.tag == "worldbody" and e.find("body") is None)):
            mj.remove(e)
    for d in mj.findall("default"):
        mj.remove(d)
    default = ET.Element("default")
    ET.SubElement(default, "joint", {"armature": "0.01", "damping": "0.3", "frictionloss": "0.1"})
    # collides with the floor only (contype 2 & floor conaffinity 1), never with itself
    ET.SubElement(default, "geom", {"contype": "2", "conaffinity": "1", "friction": "1.0 0.02 0.01"})
    ET.SubElement(default, "site", {"size": "0.01", "rgba": "1 0 0 0.5", "group": "4"})
    mj.insert(1, default)
    option = mj.find("option")
    if option is None:
        option = ET.Element("option")
        mj.insert(2, option)
    # RK4: the Euler / implicit integrators drift the angular momentum of a fast-spinning, tucking body by ~13 % in
    # half a second at 1 kHz (a backflip is exactly that); RK4 conserves it
    option.attrib.update({"timestep": "0.001", "integrator": "RK4", "cone": "elliptic", "impratio": "10"})
    mj.insert(0, ET.Element("visual"))
    ET.SubElement(mj.find("visual"), "global", {"offwidth": "1920", "offheight": "1080"})

    for geom in mj.iter("geom"):
        if geom.get("type") == "mesh" and geom.get("contype") is None:
            geom.set("group", "3")  # collision mesh, hidden
        if geom.get("size") == "0.005":  # foot spheres: stiff contact (the MPC assumes rigid ground)
            geom.attrib.update({"priority": "1", "condim": "3", "solref": "0.004 1", "solimp": "0.95 0.99 0.001"})

    # sites at the MPC contact frames (task.info contacts.contact_frame_translation) for drawing
    for side, prefix in (("left", "l"), ("right", "r")):
        body = mj.find(".//body[@name='%s_ankle_roll_link']" % side)
        ET.SubElement(body, "site", {"name": "foot_%s_contact" % prefix, "pos": "0.035 0 -0.035"})

    # joint torque limits -> motor ctrlrange
    limits = {j.get("name"): j.get("actuatorfrcrange") for j in mj.iter("joint") if j.get("actuatorfrcrange")}
    for motor in mj.find("actuator"):
        rng = limits.get(motor.get("joint"))
        if rng:
            motor.set("ctrlrange", rng)
            motor.set("ctrllimited", "true")

    ET.indent(tree, space="  ")
    with open(dst, "w") as f:
        f.write("<!-- Unitree G1, 29 DoF, torque motors. Generated by g1_backflip_mujoco/scripts/generate_model.py from\n"
                "     wb_humanoid_mpc robot_models/unitree_g1/g1_description/urdf/g1_29dof.xml (meshes from the submodule). -->\n")
        tree.write(f, encoding="unicode")


def main():
    wb = sys.argv[1] if len(sys.argv) > 1 else os.path.join(PKG, "..", "wb_humanoid_mpc")
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(PKG, "robots", "g1_29dof")
    desc = os.path.join(wb, "robot_models", "unitree_g1", "g1_description")
    os.makedirs(os.path.join(out, "urdf"), exist_ok=True)
    generate_urdf(os.path.join(desc, "urdf", "g1_29dof.urdf"), os.path.join(out, "urdf", "g1_29dof_flip.urdf"))
    mesh_rel = os.path.relpath(os.path.join(desc, "meshes"), out)
    generate_mjcf(os.path.join(desc, "urdf", "g1_29dof.xml"), os.path.join(out, "g1_29dof.xml"), mesh_rel)
    print("wrote %s (meshes: %s)" % (out, mesh_rel))
    return 0


if __name__ == "__main__":
    sys.exit(main())
